# India's national number pattern (libphonenumber): 10 digits from 2–9, or a
# 1-prefixed / 000800 special number.
_INDIA = re.compile(r"(?:000800|[2-9][0-9][0-9])[0-9]{7}|1[0-9]{7,12}")

_CODES = sorted(set(NATIONAL_LENGTHS) | {code for _, _, code in COUNTRIES}, key=len, reverse=True)
_NON_DIGITS = re.compile(r"[^0-9]")


def dial_code(iso2: str) -> str:
    return next((code for iso, _, code in COUNTRIES if iso == iso2), "91")


def split_phone(value: str) -> Tuple[Optional[str], str]:
    """``"919876543210"`` → ``("91", "9876543210")``: the longest known calling
    code the digits start with, and the rest (``None`` when none matches)."""
    digits = _NON_DIGITS.sub("", value or "")
    for code in _CODES:
        if digits.startswith(code):
            return code, digits[len(code) :]
    return None, digits


def country_for(value: str, fallback: str = DEFAULT_COUNTRY) -> str:
    """The country a stored number belongs to (the first listed for its code)."""
    code, _ = split_phone(value)
    if code is None:
        return fallback
    if code == dial_code(fallback):
        return fallback
    return next((iso for iso, _, c in COUNTRIES if c == code), fallback)


def without_trunk_zero(value: str) -> str:
    """A number typed with its national trunk "0" (UK "07911 123456", India
    "09876543210") as the web stores it — libphonenumber drops that 0 — when
    it is invalid as typed and valid without it. A 0 that belongs to the
    number (Italy's "06…") leaves it valid as typed, so it stays."""
    code, national = split_phone(value)
    if code is None or not national.startswith("0") or is_valid_phone(value):
        return value
    stripped = code + national[1:]
    return stripped if is_valid_phone(stripped) else value


def is_valid_phone(value: str) -> bool:
    text = (value or "").strip()
    if text.startswith("+"):
        text = text[1:]
    if not text or _NON_DIGITS.search(text):
        return False
    code, national = split_phone(text)
    if code is None or not national:
        return False
    if code == "91":
        return _INDIA.fullmatch(national) is not None
    allowed = NATIONAL_LENGTHS.get(code)
    if allowed is None:
        return 4 <= len(national) and 8 <= len(code) + len(national) <= 15
    return len(national) in allowed
